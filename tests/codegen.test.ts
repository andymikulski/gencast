describe('generateCodegen - outputLanguage: js', () => {
  it('writes a .gen.js file instead of .gen.ts', () => {
    const { run, exists, cleanup } = scratch(['Gun.ts']);
    try {
      run({ outputLanguage: 'js' });
      expect(exists('Gun.gen.js')).toBe(true);
      expect(exists('Gun.gen.ts')).toBe(false);
    } finally {
      cleanup();
    }
  });

  it('omits type annotations and import type statements', () => {
    const { run, dir, cleanup } = scratch(['Gun.ts']);
    try {
      run({ outputLanguage: 'js' });
      const out = fs.readFileSync(path.join(dir, 'Gun.gen.js'), 'utf8');
      expect(out).toContain('export function CastToGun(obj)');
      expect(out).not.toContain(': IGun |');
      expect(out).not.toContain('import type');
    } finally {
      cleanup();
    }
  });
});

