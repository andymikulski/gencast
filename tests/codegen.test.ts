describe('generateCodegen - removeIPrefix', () => {
  it('strips the I prefix from the function name by default', () => {
    const { run, read, cleanup } = scratch(['Gun.ts']);
    try {
      run();
      const out = read('Gun.gen.ts');
      expect(out).toContain('export function CastToGun');
      expect(out).not.toContain('export function CastToIGun');
    } finally {
      cleanup();
    }
  });

  it('keeps the I prefix when removeIPrefix is false', () => {
    const { run, read, cleanup } = scratch(['Gun.ts']);
    try {
      run({ removeIPrefix: false });
      expect(read('Gun.gen.ts')).toContain('export function CastToIGun');
    } finally {
      cleanup();
    }
  });
});

