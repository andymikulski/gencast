describe('generateCodegen - null check style', () => {
  it('emits obj != null (loose) by default', () => {
    const { run, read, cleanup } = scratch(['Gun.ts']);
    try {
      run({ strictNullCheck: false });
      const out = read('Gun.gen.ts');
      expect(out).toContain('obj != null');
      expect(out).not.toContain('obj !== null && obj !== undefined');
    } finally {
      cleanup();
    }
  });

  it('emits obj !== null && obj !== undefined when strictNullCheck is true', () => {
    const { run, read, cleanup } = scratch(['Gun.ts']);
    try {
      run({ strictNullCheck: true });
      expect(read('Gun.gen.ts')).toContain('obj !== null && obj !== undefined');
    } finally {
      cleanup();
    }
  });
});

