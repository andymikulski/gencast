describe('generateCodegen - type aliases (generateTypeCasts: true)', () => {
  it('generates casts for primitive type aliases', () => {
    const { run, read, cleanup } = scratch(['Types.ts']);
    try {
      run({ generateTypeCasts: true });
      const out = read('Types.gen.ts');
      expect(out).toContain('export function CastToID');
      expect(out).toContain('typeof(obj) === "number"');
      expect(out).toContain('export function CastToUsername');
      expect(out).toContain('typeof(obj) === "string"');
      expect(out).toContain('export function CastToIsActive');
      expect(out).toContain('typeof(obj) === "boolean"');
    } finally {
      cleanup();
    }
  });

  it('generates equality checks for string literal union types', () => {
    const { run, read, cleanup } = scratch(['Types.ts']);
    try {
      run({ generateTypeCasts: true });
      const out = read('Types.gen.ts');
      expect(out).toContain('export function CastToStatus');
      expect(out).toContain('obj === "active"');
      expect(out).toContain('obj === "inactive"');
      expect(out).toContain('obj === "pending"');
    } finally {
      cleanup();
    }
  });

  it('generates property checks for object type aliases', () => {
    const { run, read, cleanup } = scratch(['Types.ts']);
    try {
      run({ generateTypeCasts: true });
      const out = read('Types.gen.ts');
      expect(out).toContain('export function CastToPoint');
      expect(out).toContain('typeof(obj.x) === "number"');
      expect(out).toContain('typeof(obj.y) === "number"');
    } finally {
      cleanup();
    }
  });

  it('does not generate a file for a types-only file when generateTypeCasts is false', () => {
    const { run, exists, cleanup } = scratch(['Types.ts']);
    try {
      run({ generateTypeCasts: false });
      // Types.ts has no interfaces, only type aliases — nothing to generate
      expect(exists('Types.gen.ts')).toBe(false);
    } finally {
      cleanup();
    }
  });
});

