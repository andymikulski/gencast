/**
 * Integration tests for the generateCodegen() function.
 *
 * Each test creates a temporary directory, copies the relevant fixture source
 * files into it, runs the generator, and asserts on the output.  Using temp
 * dirs means the committed fixtures in tests/fixtures/ are never touched during
 * test runs.
 */
import { describe, it, expect } from 'vitest';
import fs from 'fs';
import path from 'path';
import os from 'os';

import { generateCodegen, GenCastConfig } from '../src/codegen';

const FIXTURES_DIR = path.resolve(__dirname, 'fixtures');

// ---------------------------------------------------------------------------
// Helper: spin up an isolated temp directory for one test scenario
// ---------------------------------------------------------------------------

function scratch(sourceFiles: string[], config: GenCastConfig = {}) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'gencast-test-'));

  for (const file of sourceFiles) {
    fs.copyFileSync(path.join(FIXTURES_DIR, file), path.join(dir, file));
  }

  const tsconfigPath = path.join(dir, 'tsconfig.json');
  fs.writeFileSync(
    tsconfigPath,
    JSON.stringify({
      compilerOptions: {
        target: 'ES2018',
        module: 'commonjs',
        strict: true,
        esModuleInterop: true,
        skipLibCheck: true,
        moduleResolution: 'node',
      },
      include: ['*.ts'],
    })
  );

  const run = (overrides: GenCastConfig = {}) =>
    generateCodegen({ tsconfigPath, ...config, ...overrides });

  const read = (filename: string) =>
    fs.readFileSync(path.join(dir, filename), 'utf8');

  const exists = (filename: string) =>
    fs.existsSync(path.join(dir, filename));

  const cleanup = () =>
    fs.rmSync(dir, { recursive: true, force: true });

  return { dir, run, read, exists, cleanup };
}

// ---------------------------------------------------------------------------
// Basic interface generation
// ---------------------------------------------------------------------------

describe('generateCodegen - simple interface', () => {
  it('generates a cast function with the correct signature', () => {
    const { run, read, cleanup } = scratch(['Gun.ts']);
    try {
      run();
      const out = read('Gun.gen.ts');
      expect(out).toContain('export function CastToGun(obj: any): IGun | null');
    } finally {
      cleanup();
    }
  });

  it('emits the autogenerated header', () => {
    const { run, read, cleanup } = scratch(['Gun.ts']);
    try {
      run();
      const out = read('Gun.gen.ts');
      expect(out).toContain('// This is an autogenerated file, DO NOT EDIT.');
      expect(out).toContain("generated from `Gun.ts`");
    } finally {
      cleanup();
    }
  });

  it('imports the source type', () => {
    const { run, read, cleanup } = scratch(['Gun.ts']);
    try {
      run();
      expect(read('Gun.gen.ts')).toContain("import type { IGun } from './Gun'");
    } finally {
      cleanup();
    }
  });

  it('emits typeof checks for each interface property', () => {
    const { run, read, cleanup } = scratch(['Gun.ts']);
    try {
      run();
      const out = read('Gun.gen.ts');
      expect(out).toContain('typeof(obj.caliber) === "number"');
      expect(out).toContain('typeof(obj.manufacturer) === "string"');
      expect(out).toContain('typeof(obj.ammoCapacity) === "number"');
    } finally {
      cleanup();
    }
  });

  it('produces no gen file for a file with no exportable types', () => {
    // Write a source file with only a non-exported interface
    const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'gencast-test-'));
    try {
      fs.writeFileSync(path.join(dir, 'Empty.ts'), 'interface IPrivate { x: number; }');
      const tsconfigPath = path.join(dir, 'tsconfig.json');
      fs.writeFileSync(tsconfigPath, JSON.stringify({ compilerOptions: { strict: true }, include: ['*.ts'] }));
      generateCodegen({ tsconfigPath });
      expect(fs.existsSync(path.join(dir, 'Empty.gen.ts'))).toBe(false);
    } finally {
      fs.rmSync(dir, { recursive: true, force: true });
    }
  });
});

