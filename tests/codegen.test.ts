describe('generateCodegen - failureReturnValue', () => {
  it('uses null by default', () => {
    const { run, read, cleanup } = scratch(['Gun.ts']);
    try {
      run();
      const out = read('Gun.gen.ts');
      expect(out).toContain(': IGun | null');
      expect(out).toContain('? obj : null');
    } finally {
      cleanup();
    }
  });

  it('uses undefined when configured', () => {
    const { run, read, cleanup } = scratch(['Gun.ts']);
    try {
      run({ failureReturnValue: 'undefined' });
      const out = read('Gun.gen.ts');
      expect(out).toContain(': IGun | undefined');
      expect(out).toContain('? obj : undefined');
    } finally {
      cleanup();
    }
  });
});

